#!/bin/bash

EXEC_FILE="./lab_strings"
SOURCE_FILE="2_1.c"

echo "=== Компиляция программы ==="
gcc -std=c99 -Wall -Wextra $SOURCE_FILE -o $EXEC_FILE
if [ $? -ne 0 ]; then
    echo "Ошибка компиляции!"
    exit 1
fi
echo "Успешно."
echo ""

echo "======================================================"
echo "      БЛОК 1: ВАЛИДНЫЕ ДАННЫЕ (Успешная работа)       "
echo "======================================================"

echo "[1.1] Тест флага -l (длина): 'HelloWorld'"
$EXEC_FILE -l "HelloWorld"

echo -e "\n[1.2] Тест флага -r (реверс): '123456789'"
$EXEC_FILE -r "123456789"

echo -e "\n[1.3] Тест флага -u (нечетные заглавные): 'abcdefghi'"
$EXEC_FILE -u "abcdefghi"

echo -e "\n[1.4] Тест флага -n (цифры->буквы->ост): 'a1!b2@c3#'"
$EXEC_FILE -n "a1!b2@c3#"

echo -e "\n[1.5] Тест флага -c (конкатенация, seed 42): 'A' 'B' 'C' 'D'"
$EXEC_FILE -c 42 "A" "B" "C" "D"

echo -e "\n[1.6] Тест флага -c (разные сиды дают разный результат):"
$EXEC_FILE -c 123 "Один" "Два" "Три" "Четыре"
$EXEC_FILE -c 999 "Один" "Два" "Три" "Четыре"


echo -e "\n======================================================"
echo "    БЛОК 2: НЕВАЛИДНЫЕ ДАННЫЕ (Отлов ошибок валидации)"
echo "======================================================"

echo "[2.1] Передан неизвестный флаг (-x)"
$EXEC_FILE -x "Test"
echo "Код возврата: $?"

echo -e "\n[2.2] Флаг -l, но передано слишком много аргументов"
$EXEC_FILE -l "Test" "ExtraArg"
echo "Код возврата: $?"

echo -e "\n[2.3] Флаг -c, но seed - это текст ('not_a_number')"
$EXEC_FILE -c not_a_number "Str1" "Str2"
echo "Код возврата: $?"

echo -e "\n[2.4] Флаг -c, но seed отрицательный (-5)"
$EXEC_FILE -c -5 "Str1" "Str2"
echo "Код возврата: $?"

echo -e "\n[2.5] Запуск без аргументов вообще"
$EXEC_FILE
echo "Код возврата: $?"


echo -e "\n======================================================"
echo " БЛОК 3: ПОПЫТКИ 'СЛОМАТЬ' ПРОГРАММУ (Краш-тесты)     "
echo "======================================================"

echo "[3.1] Краш-тест: передача пустой строки ('')"
$EXEC_FILE -r ""
echo "Код возврата: $?"

echo -e "\n[3.2] Краш-тест: флаг -c без строк (только seed)"
$EXEC_FILE -c 12345
echo "Код возврата (должна отработать, вернув пустую строку): $?"

echo -e "\n[3.3] Краш-тест: огромная строка для переворота"
LONG_STR=$(printf 'a%.0s' {1..50000})
$EXEC_FILE -l "$LONG_STR"
echo "Код возврата: $?"

echo -e "\n[3.4] Краш-тест: конкатенация огромного количества аргументов (около 1000)"
ARGS=$(printf '"A" %.0s' {1..1000})
eval $EXEC_FILE -c 777 $ARGS > /dev/null
echo "Программа отработала массив из 1000 аргументов без падения (вывод скрыт)."
echo "Код возврата: $?"

echo -e "\n=== ТЕСТЫ ЗАВЕРШЕНЫ ==="