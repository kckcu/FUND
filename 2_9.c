#include <stdio.h>
#include <stdlib.h>
#include <stdarg.h>
#include <math.h>

// 1. ФУНКЦИЯ-РАБОТНИК: проверяет одну конкретную дробь
int has_finite_representation(double fraction, int base) {
    // В компьютере дроби хранятся неидеально, поэтому сравнивать строго с 0 нельзя.
    // Мы задаем микроскопическую погрешность (эпсилон).
    double eps = 1e-6; 

    // Пытаемся "разрезать" дробь по правилам новой базы.
    // Делаем максимум 30 шагов. Если за 30 шагов остаток не исчезнет, дробь бесконечная.
    for (int i = 0; i < 30; i++) {
        // Если остаток практически равен нулю (с учетом погрешности), то всё отлично
        if (fraction < eps || (1.0 - fraction) < eps) {
            return 1; // Успех: дробь конечная (true)
        }

        // Умножаем на основание системы
        fraction = fraction * base;
        
        // Отбрасываем целую часть, оставляя только "крошки"
        fraction = fraction - floor(fraction); 
    }

    return 0; // Провал: крошки остались, дробь бесконечная (false)
}

// 2. ГЛАВНАЯ ФУНКЦИЯ (Начальник с переменным числом аргументов)
// Принимает: базу системы, количество дробей, и сами дроби через запятую
int* check_fractions(int base, int count, ...) {
    if (count <= 0) return NULL;

    // Выделяем память под массив ответов (1 - конечная, 0 - бесконечная)
    int* results = (int*)malloc(count * sizeof(int));
    if (!results) return NULL;

    va_list args;
    va_start(args, count);

    for (int i = 0; i < count; i++) {
        // Достаем очередную дробь из списка аргументов
        double current_fraction = va_arg(args, double);
        
        // Отдаем Работнику на проверку и записываем результат
        results[i] = has_finite_representation(current_fraction, base);
    }

    va_end(args);
    return results;
}

// 3. ДЕМОНСТРАЦИЯ РАБОТЫ (Наш встроенный тест)
int main() {
    printf("=== Проверка конечности дробей ===\n\n");

    // Тест 1: База 2 (Двоичная система). 
    // 0.25 и 0.5 - конечные, а вот 0.1 - бесконечная (уходит в период).
    int base1 = 2;
    int* res1 = check_fractions(base1, 3, 0.25, 0.5, 0.1);
    
    printf("Система счисления: %d\n", base1);
    printf("Дробь 0.25 -> %s\n", res1[0] ? "Конечная" : "Бесконечная");
    printf("Дробь 0.5  -> %s\n", res1[1] ? "Конечная" : "Бесконечная");
    printf("Дробь 0.1  -> %s\n", res1[2] ? "Конечная" : "Бесконечная");
    free(res1);
    printf("----------------------------------\n");

    // Тест 2: База 3 (Троичная система).
    // 0.3333333 (одна треть) в троичной системе - это ровно 0.1, то есть она конечная!
    // А вот 0.5 в троичной системе бесконечна.
    int base2 = 3;
    int* res2 = check_fractions(base2, 2, 0.3333333333333333, 0.5);
    
    printf("Система счисления: %d\n", base2);
    printf("Дробь 1/3 (0.33...) -> %s\n", res2[0] ? "Конечная" : "Бесконечная");
    printf("Дробь 0.5           -> %s\n", res2[1] ? "Конечная" : "Бесконечная");
    free(res2);

    return 0;
}