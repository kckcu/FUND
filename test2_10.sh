#!/bin/bash

echo "Сборка программы переразложения многочлена..."
echo "--------------------------------------------"

# Компилируем файл 2_10.c (подключаем математическую библиотеку -lm для функции fabs)
gcc 2_10.c -o app_2_10 -lm

# Проверяем, прошла ли сборка без ошибок
if [ $? -ne 0 ]; then
    echo "❌ Ошибка компиляции! Проверь код."
    exit 1
fi

echo "✅ Сборка успешна! Запускаем демонстрацию:"
echo "============================================"

# Запускаем программу
./app_2_10

echo "============================================"
echo "Демонстрация завершена. Удаляем временный файл..."
rm app_2_10
echo "Готово!"