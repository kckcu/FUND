#!/bin/bash

echo "Собираем анализатор дробей..."
echo "--------------------------------------------"

# Компилируем файл 2_5.c (флаг -lm обязателен из-за функции floor)
gcc 2_5.c -o app_2_5 -lm

# Проверяем, прошла ли сборка без ошибок
if [ $? -ne 0 ]; then
    echo "❌ Ошибка компиляции! Проверь код в 2_5.c"
    exit 1
fi

echo "✅ Сборка успешна! Запускаем:"
echo "============================================"

# Запускаем программу
./app_2_5

echo "============================================"
echo "Проверка завершена. Удаляем временный файл..."
rm app_2_5
echo "Готово!"