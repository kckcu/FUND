#!/bin/bash

SOURCE_FILE="3.c"
EXEC_FILE="3"

echo "Компиляция файла $SOURCE_FILE..."
gcc $SOURCE_FILE -o $EXEC_FILE -lm


if [ $? -ne 0 ]; then
    echo "Ошибка компиляции! Тесты остановлены."
    exit 1
fi
echo "Компиляция прошла успешно. Запуск тестов..."
echo "========================================="

echo -e "\n[--- ТЕСТЫ ДЛЯ ФЛАГА -q (Уравнения) ---]"

echo "Тест 1.1: Обычное квадратное уравнение (1x^2 - 5x + 6 = 0)"
./$EXEC_FILE -q 0.0001 1 -5 6

echo -e "\nТест 1.2: Вырождение в линейное уравнение (0x^2 + 2x - 4 = 0)"
./$EXEC_FILE -q 0.0001 0 2 -4

echo -e "\nТест 1.3: Бесконечно много решений (0x^2 + 0x + 0 = 0)"
./$EXEC_FILE -q 0.0001 0 0 0

echo -e "\nТест 1.4: Абсурдное уравнение (0x^2 + 0x + 5 = 0)"
./$EXEC_FILE -q 0.0001 0 0 5


echo -e "\n[--- ТЕСТЫ ДЛЯ ФЛАГА -m (Кратность) ---]"

echo "Тест 2.1: Числа кратны (15 и 5)"
./$EXEC_FILE -m 15 5

echo -e "\nТест 2.2: Числа не кратны (15 и 7)"
./$EXEC_FILE -m 15 7

echo -e "\nТест 2.3: Работа с отрицательными числами (-20 и 4)"
./$EXEC_FILE -m -20 4

echo -e "\nТест 2.4: Защита от деления на ноль (10 и 0)"
./$EXEC_FILE -m 10 0


echo -e "\n[--- ТЕСТЫ ДЛЯ ФЛАГА -t (Треугольник) ---]"

echo "Тест 3.1: Идеальный египетский треугольник (3, 4, 5)"
./$EXEC_FILE -t 0.0001 3 4 5

echo -e "\nТест 3.2: Треугольник существует, но не прямоугольный (4, 4, 6)"
./$EXEC_FILE -t 0.0001 4 4 6

echo -e "\nТест 3.3: Проверка работы эпсилон (погрешность дроби 4.999)"
./$EXEC_FILE -t 0.01 3.0 4.0 4.999

echo -e "\nТест 3.4: Нарушение неравенства треугольника (1, 2, 10)"
./$EXEC_FILE -t 0.0001 1 2 10

echo -e "\n========================================="
echo "Все тесты завершены!"