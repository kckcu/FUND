#!/bin/bash

SOURCE="3_2.c"
EXEC="./3_2.out"

GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m'

echo "Компиляция $SOURCE..."
gcc -std=c99 -Wall -Wextra -Werror $SOURCE -o $EXEC

if [ $? -ne 0 ]; then
    echo -e "${RED}Ошибка компиляции!${NC}"
    exit 1
fi

echo -e "${GREEN}Компиляция успешно завершена.${NC}\n"

# Функция для тестирования
# $1 - Название теста
# $2 - Входные данные (stdin)
# $3 - Ожидаемый вывод
# $4 - Ожидаемый код возврата
run_test() {
    local test_name="$1"
    local input_data="$2"
    local expected_out="$3"
    local expected_ret="$4"

    echo -n "Тест: $test_name ... "
    
    # Подаем входные данные через stdin и захватываем stdout + stderr
    actual_out=$(echo -e "$input_data" | $EXEC 2>&1)
    actual_ret=$?

    if [ "$actual_ret" -eq "$expected_ret" ] && [[ "$actual_out" == *"$expected_out"* ]]; then
        echo -e "${GREEN}ПРОЙДЕН${NC} (Вывод: $actual_out)"
    else
        echo -e "${RED}ПРОВАЛ${NC}"
        echo "   Входные данные: "
        echo -e "$input_data"
        echo "   Ожидалось: вывод содержит '$expected_out', статус $expected_ret"
        echo "   Получено : вывод '$actual_out', статус $actual_ret"
    fi
}

# --- Позитивные тесты ---

run_test "3 заявки, 1 зал (2 пересекаются, 2 поместятся)" \
"3 1\n1 10:00 11:30\n2 11:00 12:00\n3 11:30 13:00" \
"2" 0

run_test "3 заявки, 2 зала (все поместятся)" \
"3 2\n1 10:00 11:30\n2 11:00 12:00\n3 11:30 13:00" \
"3" 0

run_test "5 заявок, 2 зала (состыковка время-в-время разрешена)" \
"5 2\n1 09:00 10:00\n2 10:00 11:00\n3 09:30 10:30\n4 10:30 11:30\n5 11:00 12:00" \
"5" 0

# --- Негативные тесты ---

run_test "Некорректное значение n (n <= 0)" \
"0 2" \
"Количество заявок и залов должны быть положительными" 1

run_test "Некорректное время (25:00)" \
"1 1\n1 25:00 26:00" \
"Неверный формат времени" 1

run_test "Время начала больше окончания" \
"1 1\n1 15:00 14:00" \
"Время начала должно быть строго меньше времени окончания" 1

run_test "Отрицательный ID" \
"1 1\n-5 10:00 11:00" \
"ID доклада должен быть положительным" 1

echo -e "\nУдаление скомпилированного файла..."
rm $EXEC