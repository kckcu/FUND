#!/bin/bash
SOURCE_FILE="9.c"
EXEC_FILE="9"

echo "Компиляция файла $SOURCE_FILE..."
gcc $SOURCE_FILE -o $EXEC_FILE

if [ $? -ne 0 ]; then
    echo "Ошибка компиляции! Тесты остановлены."
    exit 1
fi
echo "Компиляция прошла успешно."
echo "========================================="

echo -e "\n[--- ТЕСТ 1: Обычный диапазон от 0 до 100 ---]"
./$EXEC_FILE 0 100

echo -e "\n[--- ТЕСТ 2: Отрицательный диапазон от -50 до -10 ---]"
./$EXEC_FILE -50 -10

echo -e "\n[--- ТЕСТ 3: Перепутанные границы (100 и 0) ---]"
echo "(Программа должна сама поменять их местами и выдать массив от 0 до 100)"
./$EXEC_FILE 100 0

echo -e "\n[--- ТЕСТ 4: Узкий диапазон (5 и 5) ---]"
echo "(Массив должен состоять только из пятерок)"
./$EXEC_FILE 5 5

echo -e "\n[--- ТЕСТ 5: Ошибка пользователя (запуск без аргументов) ---]"
./$EXEC_FILE

echo -e "\n========================================="
echo "Все тесты завершены!"