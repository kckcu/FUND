#!/bin/bash

echo "Сборка программы студентов..."
gcc 3_5.c -o app_3_5

if [ $? -ne 0 ]; then
    echo "❌ Ошибка компиляции!"
    exit 1
fi

echo "Создаем тестовую базу студентов..."
# Формат: ID Имя Фамилия Группа Оценка1 Оценка2 Оценка3 Оценка4 Оценка5
cat <<EOF > students.txt
101 Ivan Ivanov M8O-201 4 5 4 5 5
102 Petr Petrov M8O-201 3 3 4 3 4
103 Anna Smirnova M8O-202 5 5 5 5 5
104 John Doe M8O-202 2 3 2 3 4
EOF

# Очищаем файл трассировки перед запуском
> trace.txt

echo "✅ Запуск программы (авто-ввод):"
echo "============================================"

# Передаем два аргумента: файл для чтения и файл трассировки
./app_3_5 students.txt trace.txt <<EOF
4
3
2
4
1
103
2
5
EOF

echo "============================================"
echo "Содержимое файла трассировки (trace.txt):"
cat trace.txt

echo "Удаление временных файлов..."
rm app_3_5 students.txt trace.txt
echo "Готово!"