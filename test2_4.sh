#!/bin/bash

# 1. Компилируем программу и называем итоговый файл 2_4
gcc 2_4.c -o 2_4

# Проверяем, успешно ли прошла компиляция
if [ $? -ne 0 ]; then
    echo "Ошибка компиляции!"
    exit 1
fi

echo "Компиляция успешна! Начинаем тестирование..."
echo "============================================"

echo ">>> ТЕСТ 1: Хитрый выбор (Из условия)"
echo "Ожидание: возьмет file_B и file_C (вес 10, важность 16)"
echo "--------------------------------------------"
./2_4 <<EOF
3 10
file_A 6 10
file_B 5 8
file_C 5 8
EOF
echo "============================================"

echo ">>> ТЕСТ 2: Идеальное совпадение"
echo "Ожидание: возьмет оба файла (вес 5, важность 25)"
echo "--------------------------------------------"
./2_4 <<EOF
2 5
file1.txt 2 10
file2.txt 3 15
EOF
echo "============================================"

echo ">>> ТЕСТ 3: Нулевая вместимость флешки"
echo "Ожидание: ничего не влезет (вес 0, важность 0)"
echo "--------------------------------------------"
./2_4 <<EOF
1 0
too_big_file 5 100
EOF
echo "============================================"

echo ">>> ТЕСТ 4: Файлы больше вместимости"
echo "Ожидание: ничего не возьмет, так как оба файла слишком большие"
echo "--------------------------------------------"
./2_4 <<EOF
2 3
heavy_1 5 10
heavy_2 4 20
EOF
echo "============================================"

# Удаляем
rm 2_4