#!/bin/bash

echo "Начинаем сборку программы выставки собак..."
echo "--------------------------------------------"

# 1. Компилируем твой основной файл прямо отсюда. 
# Флаг -lm обязателен, потому что судьи используют математику (корень и степень)
gcc 2_7.c -o app_2_7 -lm

# 2. Проверяем, не было ли ошибок при компиляции
if [ $? -ne 0 ]; then
    echo "❌ Ошибка компиляции! Проверь код в 2_7.c"
    exit 1
fi

echo "✅ Компиляция успешна! Запускаем выставку:"
echo "============================================"

# 3. Запускаем скомпилированную программу
./app_2_7

echo "============================================"
echo "Выставка завершена. Убираем мусор..."

# 4. Удаляем временный файл программы
rm app_2_7

echo "Готово!"